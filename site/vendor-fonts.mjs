// Vendors the web fonts into assets/fonts/ (committed) so the site makes no
// third-party request. Run deliberately, not from `pnpm build`.
import { mkdir, writeFile, rm } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "assets", "fonts");

// Google serves woff2 only to a browser UA; the default fetch() UA gets truetype.
const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

const FAMILIES = [
  { name: "Inter", css: "Inter:wght@400;500;600;700" },
  { name: "Geist Mono", css: "Geist+Mono:wght@400;500" },
];

const KEEP_SUBSETS = new Set(["latin", "latin-ext"]);

function parseFaces(css) {
  const faces = [];
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  let m;
  while ((m = re.exec(css)) !== null) {
    const subset = m[1];
    const block = m[2];
    const family = (block.match(/font-family:\s*'([^']+)'/) || [])[1];
    const weight = (block.match(/font-weight:\s*(\d+)/) || [])[1];
    const style = (block.match(/font-style:\s*(\w+)/) || [])[1] || "normal";
    const url = (block.match(/url\((https:\/\/[^)]+\.woff2)\)/) || [])[1];
    const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1];
    if (!family || !weight || !url) continue;
    faces.push({ subset, family, weight, style, url, range: range && range.trim() });
  }
  return faces;
}

async function get(url, as) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return as === "buffer" ? Buffer.from(await res.arrayBuffer()) : res.text();
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

async function main() {
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  const rules = [];
  let bytes = 0;
  let skipped = 0;

  for (const fam of FAMILIES) {
    const css = await get(
      `https://fonts.googleapis.com/css2?family=${fam.css}&display=swap`,
      "text"
    );
    const faces = parseFaces(css);
    if (!faces.length) throw new Error(`no @font-face rules parsed for ${fam.name}`);

    for (const f of faces) {
      if (!KEEP_SUBSETS.has(f.subset)) {
        skipped++;
        continue;
      }
      const file = `${slug(f.family)}-${f.weight}-${f.subset}.woff2`;
      const buf = await get(f.url, "buffer");
      await writeFile(join(OUT, file), buf);
      bytes += buf.length;
      rules.push(
        `@font-face {\n` +
          `  font-family: '${f.family}';\n` +
          `  font-style: ${f.style};\n` +
          `  font-weight: ${f.weight};\n` +
          `  font-display: swap;\n` +
          `  src: url('/assets/fonts/${file}') format('woff2');\n` +
          (f.range ? `  unicode-range: ${f.range};\n` : "") +
          `}`
      );
      console.log(`  ${file}  ${(buf.length / 1024).toFixed(1)} KB`);
    }
  }

  const header =
    `/* Generated by site/vendor-fonts.mjs — do not edit by hand.\n` +
    `   Self-hosted so the published site makes no third-party font request.\n` +
    `   Subsets: ${[...KEEP_SUBSETS].join(", ")}. Re-run the script to refresh. */\n\n`;
  await writeFile(join(OUT, "fonts.css"), header + rules.join("\n\n") + "\n");

  console.log(
    `\n${rules.length} faces, ${(bytes / 1024).toFixed(0)} KB total ` +
      `(${skipped} non-latin subset faces skipped)`
  );
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
